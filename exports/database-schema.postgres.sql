-- ZadkAI PostgreSQL reference schema.
-- The current application runtime is MySQL/TiDB; port the Drizzle adapter before using this schema in production.

CREATE TABLE IF NOT EXISTS users (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "openId" varchar(64) NOT NULL UNIQUE,
  name text,
  email varchar(320),
  "loginMethod" varchar(64),
  role varchar(10) NOT NULL DEFAULT 'user' CHECK (role IN ('user', 'admin')),
  "createdAt" timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "updatedAt" timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "lastSignedIn" timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS profiles (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "userId" integer NOT NULL UNIQUE,
  "calorieGoal" integer NOT NULL DEFAULT 2139,
  "proteinGoal" integer NOT NULL DEFAULT 98,
  "carbsGoal" integer NOT NULL DEFAULT 293,
  "fatGoal" integer NOT NULL DEFAULT 64,
  age integer,
  "heightCm" integer,
  "weightKg" integer,
  "startWeightKg" integer,
  "targetWeightKg" integer,
  "targetDate" date,
  "activityLevel" varchar(12) NOT NULL DEFAULT 'moderate' CHECK ("activityLevel" IN ('sedentary','light','moderate','high')),
  goal varchar(10) NOT NULL DEFAULT 'maintain' CHECK (goal IN ('lose','maintain','gain')),
  "historyMealTypeFilter" varchar(12) NOT NULL DEFAULT 'all' CHECK ("historyMealTypeFilter" IN ('all','breakfast','lunch','dinner','snack')),
  "historyCalorieFilter" varchar(12) NOT NULL DEFAULT 'all' CHECK ("historyCalorieFilter" IN ('all','under400','400to700','over700')),
  "historySortOrder" varchar(16) NOT NULL DEFAULT 'latest' CHECK ("historySortOrder" IN ('latest','caloriesDesc')),
  "preferredEatingMethod" varchar(10) NOT NULL DEFAULT 'nothing' CHECK ("preferredEatingMethod" IN ('bread','spoon','nothing')),
  "updatedAt" timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS meals (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "userId" integer NOT NULL,
  "mealName" varchar(180) NOT NULL,
  description text,
  "mealType" varchar(12) NOT NULL DEFAULT 'snack' CHECK ("mealType" IN ('breakfast','lunch','dinner','snack')),
  calories integer NOT NULL DEFAULT 0,
  protein integer NOT NULL DEFAULT 0,
  carbs integer NOT NULL DEFAULT 0,
  fat integer NOT NULL DEFAULT 0,
  fiber integer NOT NULL DEFAULT 0,
  sugar integer NOT NULL DEFAULT 0,
  sodium integer NOT NULL DEFAULT 0,
  confidence integer NOT NULL DEFAULT 0,
  "aiSummary" text,
  "imageKey" varchar(512),
  "imageUrl" varchar(768),
  "createdAt" timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS "frequentMeals" (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "userId" integer NOT NULL,
  name varchar(180) NOT NULL,
  "itemsSnapshot" text NOT NULL,
  "mealType" varchar(12) NOT NULL DEFAULT 'snack' CHECK ("mealType" IN ('breakfast','lunch','dinner','snack')),
  calories integer NOT NULL DEFAULT 0,
  protein integer NOT NULL DEFAULT 0,
  carbs integer NOT NULL DEFAULT 0,
  fat integer NOT NULL DEFAULT 0,
  fiber integer NOT NULL DEFAULT 0,
  sugar integer NOT NULL DEFAULT 0,
  sodium integer NOT NULL DEFAULT 0,
  "createdAt" timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS "weightLogs" (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "userId" integer NOT NULL,
  "weightKg" integer NOT NULL,
  "loggedAt" timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);
